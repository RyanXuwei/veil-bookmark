// Regenerates src/locales.ts and public/_locales from i18n/translations.tsv.
// Columns: zh-TW (source key) | en | ja. zh-CN is derived with OpenCC (tw -> cn).
// Requires: npm install --no-save opencc-js
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import * as OpenCC from "opencc-js";
const toCN = OpenCC.Converter({ from: "twp", to: "cn" });
const rows = readFileSync("i18n/translations.tsv", "utf8")
  .split(/\r?\n/)
  .filter(Boolean)
  .map((l) => l.split("|"));
const dict = {};
for (const [zh, en, ja] of rows) {
  if (!en || !ja) throw Error("Incomplete row: " + zh);
  dict[zh] = { "zh-CN": toCN(zh), en, ja };
}
writeFileSync(
  "src/locales.ts",
  "// Generated by scripts/build-i18n.mjs — edit i18n/translations.tsv instead.\n" +
    'export const LOCALES: Record<string, Record<"zh-CN" | "en" | "ja", string>> = ' +
    JSON.stringify(dict, null, 1) +
    ";\n",
);
const manifestName = "Veil Bookmark — 私密書籤";
const manifestDesc =
  "一般與無痕視窗皆可使用的加密私人書籤。Developed by BitingBox Studio.";
const actionTitle = "開啟 Veil Bookmark";
for (const [dir, lang] of [
  ["zh_TW", null],
  ["zh_CN", "zh-CN"],
  ["en", "en"],
  ["ja", "ja"],
]) {
  const pick = (k) => (lang ? dict[k][lang] : k);
  mkdirSync(`public/_locales/${dir}`, { recursive: true });
  writeFileSync(
    `public/_locales/${dir}/messages.json`,
    JSON.stringify(
      {
        appName: { message: pick(manifestName) },
        appDesc: { message: pick(manifestDesc) },
        actionTitle: { message: pick(actionTitle) },
      },
      null,
      2,
    ) + "\n",
  );
}
console.log(`i18n: ${rows.length} strings × 4 languages`);
